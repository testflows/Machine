"""TestFlows Machine SDK, version 1.

A program starts from one client::

    import testflows.machine.v1 as machine

    client = machine.Client()
    with client.sessions.create("ci-1", cpus=4) as session:
        client.sessions.use(session)
        run = client.create("app", disk="app")
        run.run(until="tasks")
        run.checkpoint("boot")
        branch = run.fork(at="^boot")

The SDK mirrors the `machine` command. A top-level command is a method of
`Client`, a command group is an attribute, and a command that takes a run is
a method of `Run`, with the run dropped: `machine fork app --at ^boot` is
`run.fork(at="^boot")`. Positional operands stay positional and flags are
keyword arguments.

Everything public is importable from this module. Names that start with an
underscore, and every module outside `testflows.machine.v1`, are not part of
the API and change without notice.
"""

